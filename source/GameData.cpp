void initGameData()
{
    for (int r = 0; r < 50; r++)
    {
        // casenemy[level][0-14]
        for (int t = 0; t < 15; t++)
            casenemy[r][t] = enelist[r][t];

        // spec[level]
        spec[r].ai1 = enelist[r][15];
        spec[r].ai2 = enelist[r][16];
        spec[r].aim = enelist[r][17];
        spec[r].fireRate = enelist[r][18];
        spec[r].energyDecreaser = enelist[r][19];
        spec[r].numEnemy = enelist[r][20];
        spec[r].numGuest = enelist[r][21];

        // lev[level]
        lev[r].credits = levdata[r][0];
        for (int s = 0; s < 15; s++)
            lev[r].scenario[s] = levdata[r][s + 1];
    }
}